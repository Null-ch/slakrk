export function workoutExercises(
  kind: Workout['kind'],
  equipment: boolean,
  date: string,
  load: ReturnType<typeof trainingLoad>,
): Exercise[] {
  const bank = equipment ? dumbbell : body
  const groups: Group[] = kind === 'А'
    ? [bank.squat, bank.push, bank.core, bank.back, bank.accessory]
    : [bank.hinge, bank.back, bank.core, bank.push, bank.accessory]
  const count = load.gentle ? 3 : load.sets >= 3 ? 5 : 4
  const day = Math.floor(Date.parse(date) / 86_400_000)
  let rotation = day

  return groups.slice(0, count).map((group, position) => {
    const options = load.gentle ? group.filter((option) => !option.standard) : group
    // Advance later groups daily as well as when the preceding group wraps.
    const slot = position === 0 ? rotation : rotation + day
    const index = ((slot % options.length) + options.length) % options.length
    rotation = Math.floor(rotation / options.length)
    const { name, technique, side } = options[index]!
    return {
      name, technique, target: load.target + (side ? ' на сторону' : ''),
      reps: Array<null>(load.sets).fill(null),
    }
  })
}
